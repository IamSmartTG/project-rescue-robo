"""Generate a low-poly prone-human OBJ for use as a victim prop.

The victim was a cuboid because Isaac Lab's mesh spawners are primitives only and
RigidBodyBaseCfg has no angular damping, so a capsule would roll down slopes. Body
proportions helped the LiDAR return but it still reads as a crate on screen.

MeshConverterCfg accepts an OBJ and converts it to USD with rigid-body and collision
properties, which sidesteps the primitive-only limit entirely. This writes a casualty lying
face-up: head, torso, two arms, two legs. Six boxes, 48 vertices -- deliberately crude,
because at 16x16 thermal resolution and 288 LiDAR rays nothing finer would survive sampling,
and every extra triangle costs raycast time across 4096 environments.

Lying flat and roughly slab-shaped, so a convex-hull collider behaves like the cuboid did:
it settles instead of rolling.

Usage:
    python3 harness/make_victim_mesh.py --out victim_prone.obj
"""

import argparse

# (centre_x, centre_y, centre_z, size_x, size_y, size_z) in metres, +X = head to toe.
# Origin at body centre. Total length ~1.75 m, shoulder width ~0.45 m, ~0.30 m tall.
PARTS = [
    ("head", 0.78, 0.00, 0.02, 0.20, 0.17, 0.20),
    ("torso", 0.30, 0.00, 0.00, 0.75, 0.36, 0.26),
    ("hips", -0.15, 0.00, 0.00, 0.25, 0.34, 0.24),
    ("leg_l", -0.55, 0.10, -0.01, 0.65, 0.15, 0.20),
    ("leg_r", -0.55, -0.10, -0.01, 0.65, 0.15, 0.20),
    ("arm_l", 0.28, 0.24, -0.02, 0.60, 0.12, 0.14),
    ("arm_r", 0.28, -0.24, -0.02, 0.60, 0.12, 0.14),
]

# Unit cube corners, then the 12 triangles that close it (1-indexed per OBJ, offset later).
_CORNERS = [
    (-0.5, -0.5, -0.5), (0.5, -0.5, -0.5), (0.5, 0.5, -0.5), (-0.5, 0.5, -0.5),
    (-0.5, -0.5, 0.5), (0.5, -0.5, 0.5), (0.5, 0.5, 0.5), (-0.5, 0.5, 0.5),
]
_FACES = [
    (1, 2, 3), (1, 3, 4),  # bottom
    (5, 7, 6), (5, 8, 7),  # top
    (1, 6, 2), (1, 5, 6),  # -Y
    (2, 7, 3), (2, 6, 7),  # +X
    (3, 8, 4), (3, 7, 8),  # +Y
    (4, 5, 1), (4, 8, 5),  # -X
]


def build_obj() -> str:
    lines = ["# prone casualty, generated by harness/make_victim_mesh.py"]
    offset = 0
    for name, cx, cy, cz, sx, sy, sz in PARTS:
        lines.append(f"o {name}")
        for ux, uy, uz in _CORNERS:
            lines.append(f"v {cx + ux * sx:.4f} {cy + uy * sy:.4f} {cz + uz * sz:.4f}")
        for a, b, c in _FACES:
            lines.append(f"f {a + offset} {b + offset} {c + offset}")
        offset += len(_CORNERS)
    return "\n".join(lines) + "\n"


def demo() -> None:
    """Self-check: the mesh must be closed, correctly sized, and centred."""
    obj = build_obj()
    verts = [tuple(map(float, l.split()[1:])) for l in obj.splitlines() if l.startswith("v ")]
    faces = [l for l in obj.splitlines() if l.startswith("f ")]

    assert len(verts) == len(PARTS) * 8, f"expected {len(PARTS) * 8} verts, got {len(verts)}"
    assert len(faces) == len(PARTS) * 12, f"expected {len(PARTS) * 12} faces, got {len(faces)}"

    xs = [v[0] for v in verts]
    ys = [v[1] for v in verts]
    zs = [v[2] for v in verts]
    length, width, height = max(xs) - min(xs), max(ys) - min(ys), max(zs) - min(zs)

    # Adult prone body, and flat enough that a convex hull will not roll.
    assert 1.6 <= length <= 1.9, f"body length {length:.2f} m out of range"
    assert 0.40 <= width <= 0.60, f"body width {width:.2f} m out of range"
    assert 0.20 <= height <= 0.40, f"body height {height:.2f} m out of range"
    assert height < width < length, "should be a lying body, not standing or spherical"

    # Face indices must all reference existing vertices.
    for f in faces:
        for idx in map(int, f.split()[1:]):
            assert 1 <= idx <= len(verts), f"face index {idx} out of range"

    print(f"OK  {len(verts)} verts, {len(faces)} tris, "
          f"{length:.2f} x {width:.2f} x {height:.2f} m")


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--out", default="victim_prone.obj")
    p.add_argument("--check", action="store_true", help="run the self-check only")
    a = p.parse_args()
    demo()
    if not a.check:
        with open(a.out, "w") as fh:
            fh.write(build_obj())
        print(f"wrote {a.out}")
